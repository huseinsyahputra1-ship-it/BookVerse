<?php

session_start();

/*
|--------------------------------------------------------------------------
| Validasi ID Buku
|--------------------------------------------------------------------------
*/

if (
    !isset($_GET['id']) ||
    !is_numeric($_GET['id'])
) {
    header("Location: cart.php");
    exit();
}

$book_id = (int) $_GET['id'];

/*
|--------------------------------------------------------------------------
| Hapus Buku dari Cart
|--------------------------------------------------------------------------
*/

if (isset($_SESSION['cart'][$book_id])) {
    unset($_SESSION['cart'][$book_id]);
}

/*
|--------------------------------------------------------------------------
| Kembali ke Cart
|--------------------------------------------------------------------------
*/

header("Location: cart.php");
exit();